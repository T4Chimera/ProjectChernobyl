#!/usr/bin/env python3
"""Build and refresh the dedicated GitHub Pages /docs distribution."""
from pathlib import Path
import shutil
import subprocess

root = Path(__file__).resolve().parents[1]
subprocess.run(["npm", "test"], cwd=root / "web", check=True)
subprocess.run(["npm", "run", "build"], cwd=root / "web", check=True)
target = root / "docs"
marker = target / ".generated-chernobyl-pages"
if target.exists() and not marker.exists():
    raise SystemExit("Refusing to replace unknown docs directory; preserve it before generating Pages output.")
if target.exists():
    shutil.rmtree(target)
shutil.copytree(root / "web/dist", target)
marker.write_text("Generated by tools/build-web-pages.py; edit web/ source instead.\n")
(target / ".nojekyll").touch()
print("Refreshed GitHub Pages distribution in docs/.")
